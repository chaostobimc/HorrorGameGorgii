def _damask_motif(period=512):
    """One repeating damask ornament tile (drawn at high res, returned as mask)."""
    R = period * 2
    img = Image.new("L", (R, R), 0)
    d = ImageDraw.Draw(img)
    c = R // 2
    sc = R / 512.0

    def S(v):
        return v * sc

    # central palmette
    d.ellipse([c - S(30), c - S(230), c + S(30), c + S(30)], fill=255)
    for r, w in ((S(120), 7), (S(170), 5), (S(210), 4)):
        d.ellipse([c - r, c - r, c + r, c + r], outline=255, width=int(w))
    for a in range(0, 360, 45):
        rad = math.radians(a)
        px, py = c + math.cos(rad) * S(120), c + math.sin(rad) * S(120)
        d.polygon(
            [
                (px + math.cos(rad) * S(70), py + math.sin(rad) * S(70)),
                (px + math.cos(rad + 0.5) * S(30), py + math.sin(rad + 0.5) * S(30)),
                (px + math.cos(rad - 0.5) * S(30), py + math.sin(rad - 0.5) * S(30)),
            ],
            fill=255,
        )
    # curling acanthus stems
    for sx in (-1, 1):
        d.arc(
            [c + sx * S(40) - S(130), c - S(40) - S(130), c + sx * S(40) + S(130), c - S(40) + S(130)],
            200 if sx < 0 else 340,
            340 if sx < 0 else 480,
            fill=255,
            width=int(S(9)),
        )
        d.arc(
            [c + sx * S(120) - S(90), c + S(150) - S(90), c + sx * S(120) + S(90), c + S(150) + S(90)],
            0,
            200,
            fill=255,
            width=int(S(7)),
        )
    # small diamond accents filling the corners
    for ox, oy in ((-1, -1), (1, -1), (-1, 1), (1, 1)):
        cx, cy = c + ox * S(190), c + oy * S(190)
        d.polygon(
            [(cx, cy - S(34)), (cx + S(24), cy), (cx, cy + S(34)), (cx - S(24), cy)],
            outline=255,
            width=int(S(6)),
        )
        d.ellipse([cx - S(8), cy - S(8), cx + S(8), cy + S(8)], fill=255)
    tile = img.crop((R // 4, R // 4, R // 4 + period * 2, R // 4 + period * 2)).resize(
        (period, period), Image.LANCZOS
    )
    return tile


def tex_wall_wallpaper():
    """Muted sage damask: mirrored-ink motif printed on aged paper."""
    S = 1024
    period = 512
    # build one motif tile from horizontally+vertically mirrored noise
    tile_n = 512
    n = fbm(tile_n, tile_n, 3, 3, octaves=5, seed=545)
    n = blur(n, 1.5)
    quad = n[: tile_n // 2, : tile_n // 2]
    mirrored = np.zeros((tile_n, tile_n), np.float32)
    mirrored[: tile_n // 2, : tile_n // 2] = quad
    mirrored[: tile_n // 2, tile_n // 2 :] = quad[:, ::-1]
    mirrored[tile_n // 2 :, : tile_n // 2] = quad[::-1, :]
    mirrored[tile_n // 2 :, tile_n // 2 :] = quad[::-1, ::-1]
    motif_tile = smoothstep(0.47, 0.60, mirrored)
    motif_tile = blur(motif_tile, 1.0)
    rim = np.clip(blur(motif_tile, 3.0) - motif_tile, 0, 1)

    tile_img = Image.fromarray((motif_tile * 255).astype(np.uint8))
    rim_img = Image.fromarray((np.clip(rim * 255 * 1.4, 0, 255)).astype(np.uint8))

    full = Image.new("L", (S, S), 0)
    rimfull = Image.new("L", (S, S), 0)
    for ty in range(0, S, period):
        offset = (ty // period % 2) * period // 2
        for tx in range(-period, S + period, period):
            full.paste(tile_img, (tx + offset, ty))
            rimfull.paste(rim_img, (tx + offset, ty))
    motif = np.asarray(full).astype(np.float32) / 255.0
    motif_rim = np.asarray(rimfull).astype(np.float32) / 255.0

    n2 = fbm(S, S, 2, 2, octaves=6, seed=131)
    base_col = np.array([0.50, 0.505, 0.445]) * (0.92 + 0.16 * n2[..., None])
    motif_col = np.array([0.375, 0.395, 0.325])
    img = base_col * (1 - 0.50 * motif[..., None]) + motif_col * (0.50 * motif[..., None])
    img *= (1.0 + 0.10 * motif_rim[..., None])          # printed edge highlight
    img *= (1.0 - 0.22 * motif[..., None] * 0.0 + 0.0)

    # narrow vertical stripes, the way wallpaper is hung in strips
    ys, xs = np.mgrid[0:S, 0:S] / S
    stripe = 0.5 + 0.5 * np.cos(xs * math.pi * 2 * (S / 512.0))
    img *= (0.975 + 0.05 * stripe[..., None])

    damp = smoothstep(0.05, 0.95, 1.0 - ys + 0.3 * fbm(S, S, 5, 5, octaves=4, seed=7))
    damp = np.clip(damp, 0, 1) ** 1.9
    img = img * (1 - 0.40 * damp[..., None]) + np.array([0.245, 0.225, 0.165]) * (0.40 * damp[..., None])

    mold = smoothstep(0.74, 0.92, fbm(S, S, 9, 9, octaves=6, seed=19))
    mold = blur(mold, 3.0)
    img = img * (1 - 0.5 * mold[..., None]) + np.array([0.14, 0.155, 0.10]) * (0.5 * mold[..., None])

    peel_img = Image.new("L", (S, S), 0)
    pd = ImageDraw.Draw(peel_img)
    for _ in range(4):
        cx, cy = rng.integers(120, S - 120, 2)
        pts = []
        steps = int(rng.integers(12, 20))
        rad0 = float(rng.uniform(30, 80))
        for i in range(steps):
            a = 2 * math.pi * i / steps
            r = rad0 * float(rng.uniform(0.6, 1.35))
