def _wood_tex(name, dark, seed, rings_scale=1.0, planks=0):
    S = 512
    warpv = fbm(S, S, 3, 6, octaves=4, seed=seed)
    grain = fbm(S, S, 90, 24, octaves=4, seed=seed + 1)
    rings = 1.0 - np.abs(np.sin((warpv * 14.0 + grain * 3.0) * rings_scale))
    rings = rings**1.6
    col = dark * (0.72 + 0.55 * rings[..., None])
    col *= (0.88 + 0.24 * grain[..., None])
    # varnish sheen variation
    sheen = fbm(S, S, 2, 2, octaves=3, seed=seed + 5)
    col *= (0.9 + 0.2 * sheen[..., None])
    if planks:
        hgt = rings * 0.5
        for i in range(planks):
            y = int(i * S / planks)
            col[max(0, y - 1) : y + 2, :] *= 0.4
            hgt[max(0, y - 1) : y + 2, :] = 0.0
    else:
        hgt = rings * 0.5 + grain * 0.2
    col += grain_overlay(S, S, seed + 3, 0.05)[..., None]
    save(name, col, height=hgt, normal_strength=1.6)


