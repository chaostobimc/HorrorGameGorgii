def tex_wall_brick():
    S = 1024
    bw, bh = S // 4, S // 12
    col = np.zeros((S, S, 3), np.float32)
    hgt = np.zeros((S, S), np.float32)
    mortar = np.ones((S, S), np.float32)
    for row in range(12):
        y0 = row * bh
        off = 0 if row % 2 == 0 else bw // 2
        for col_i in range(-1, 4):
            x0 = col_i * bw + off
            x1 = x0 + bw
            tone = 0.8 + 0.5 * rng.random()
            base = np.array([0.30, 0.285, 0.265]) * tone
            ys0, ys1 = y0, y0 + bh
            xs0, xs1 = max(0, x0), min(S, x1)
            if xs1 <= xs0:
                continue
            n = fbm(S, S, 30, 30, octaves=4, seed=int(tone * 1000) + row)
            patch = base * (0.8 + 0.4 * n[ys0:ys1, xs0:xs1, None])
            col[ys0:ys1, xs0:xs1] = patch
            hgt[ys0:ys1, xs0:xs1] = 0.6 + 0.2 * n[ys0:ys1, xs0:xs1]
            mortar[ys0:ys1, xs0:xs1] = 0.0
            mortar[ys0 : ys0 + 3, xs0:xs1] = 1.0
            mortar[ys0:ys1, xs0 : xs0 + 3] = 1.0
    mortar = blur(mortar, 1.2)
    mortar_col = np.array([0.33, 0.31, 0.28])
    col = col * (1 - mortar[..., None]) + mortar_col * mortar[..., None]
    hgt = hgt * (1 - mortar) - mortar * 0.4
    moss = smoothstep(0.55, 0.9, fbm(S, S, 7, 7, octaves=6, seed=91))
    col = col * (1 - 0.75 * moss[..., None]) + np.array([0.075, 0.11, 0.055]) * (0.75 * moss[..., None])
    wet = smoothstep(0.3, 0.1, fbm(S, S, 3, 3, octaves=4, seed=93))
    col *= (1 - 0.3 * wet[..., None])
    col += grain_overlay(S, S, 7, 0.05)[..., None]
    save("wall_brick", col, height=hgt, normal_strength=2.4)


