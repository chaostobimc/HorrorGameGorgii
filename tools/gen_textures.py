def _smooth(t):
    return t * t * (3.0 - 2.0 * t)


def vnoise(h, w, fy, fx, seed):
    """Tileable value noise. fy/fx are the lattice frequencies."""
    r = np.random.default_rng(seed)
    gh, gw = max(2, int(fy)), max(2, int(fx))
    g = r.random((gh, gw)).astype(np.float32)
    ys = np.arange(h, dtype=np.float32) * (gh / h)
    xs = np.arange(w, dtype=np.float32) * (gw / w)
    y0 = np.floor(ys).astype(np.int32)
    x0 = np.floor(xs).astype(np.int32)
    ty = _smooth(ys - y0)[:, None]
    tx = _smooth(xs - x0)[None, :]
    y1 = (y0 + 1) % gh
    x1 = (x0 + 1) % gw
    a = g[np.ix_(y0, x0)]
    b = g[np.ix_(y0, x1)]
    c = g[np.ix_(y1, x0)]
    d = g[np.ix_(y1, x1)]
    return (a * (1 - tx) + b * tx) * (1 - ty) + (c * (1 - tx) + d * tx) * ty


def fbm(h, w, fy, fx, octaves=5, seed=1, persistence=0.5, lacunarity=2.0):
    total = np.zeros((h, w), np.float32)
    amp = 1.0
    norm = 0.0
    f_y, f_x = fy, fx
    for i in range(octaves):
        total += amp * vnoise(h, w, f_y, f_x, seed + i * 977)
        norm += amp
        amp *= persistence
        f_y *= lacunarity
        f_x *= lacunarity
    return total / norm


def ridged(h, w, fy, fx, octaves=4, seed=1, sharpness=1.0):
    n = fbm(h, w, fy, fx, octaves=octaves, seed=seed)
    return np.clip(1.0 - np.abs(n * 2.0 - 1.0), 0.0, 1.0) ** sharpness


def warp(field, dx, dy):
    """Domain warp a 2d field by +/-dx, +/-dy (wrapping)."""
    h, w = field.shape
    xs, ys = np.meshgrid(np.arange(w), np.arange(h))
    xs = (xs + (dx * (w - 1))).astype(np.int32) % w
    ys = (ys + (dy * (h - 1))).astype(np.int32) % h
    return field[ys, xs]


def hsv_mix(a, b, t):
    t = t[..., None]
    return a * (1.0 - t) + b * t


def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / max(1e-6, (e1 - e0)), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def to_img(arr, mode="RGB"):
    a = np.clip(arr, 0.0, 1.0)
    if a.ndim == 2:
        a = np.stack([a] * 3, -1)
    return Image.fromarray((a * 255.0 + 0.5).astype(np.uint8), mode)


def blur(arr, radius):
    img = Image.fromarray((np.clip(arr, 0, 1) * 255).astype(np.uint8), "L")
    img = img.filter(ImageFilter.GaussianBlur(radius))
    return np.asarray(img).astype(np.float32) / 255.0


def blur_rgba(img, radius):
    return img.filter(ImageFilter.GaussianBlur(radius))


def normal_from_height(hgt, strength=2.0):
    """Sobel-ish normal map from a height field."""
    gy, gx = np.gradient(hgt.astype(np.float32) * strength)
    nz = np.ones_like(gx)
    ln = np.sqrt(gx * gx + gy * gy + nz * nz)
    nx = (-gx / ln) * 0.5 + 0.5
    ny = (gy / ln) * 0.5 + 0.5
    nz = (nz / ln) * 0.5 + 0.5
    return np.stack([nx, ny, nz], -1)


def save(name, arr, height=None, normal_strength=2.0, mode="RGB"):
    img = to_img(arr, mode)
    img.save(os.path.join(OUT, name + ".png"), optimize=True)
    if height is not None:
        nrm = normal_from_height(height, normal_strength)
        to_img(nrm).save(os.path.join(OUT, name + "_n.png"), optimize=True)
    print("  ->", name)


def save_alpha(name, rgb, alpha):
    h, w = alpha.shape
    out = np.zeros((h, w, 4), np.float32)
    out[..., :3] = np.clip(rgb, 0, 1)
    out[..., 3] = np.clip(alpha, 0, 1)
    Image.fromarray((out * 255).astype(np.uint8), "RGBA").save(
        os.path.join(OUT, name + ".png"), optimize=True
    )
    print("  ->", name + " (rgba)")


def line_mask(size, drawfn, blur_px=0.0):
    img = Image.new("L", (size, size), 0)
    d = ImageDraw.Draw(img)
    drawfn(d)
    if blur_px > 0:
        img = img.filter(ImageFilter.GaussianBlur(blur_px))
    return np.asarray(img).astype(np.float32) / 255.0


