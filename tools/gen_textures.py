def grain_overlay(h, w, seed, amount=0.06, fine=1.0):
    n = vnoise(h, w, int(h * 0.45 * fine), int(w * 0.45 * fine), seed)
    n2 = vnoise(h, w, int(h * 1.5 * fine), int(w * 1.5 * fine), seed + 11)
    return (n * 0.6 + n2 * 0.4 - 0.5) * amount


def grime(h, w, seed, amount=0.5, scale=4):
    n = fbm(h, w, scale, scale, octaves=5, seed=seed)
    n = smoothstep(0.35, 0.85, n)
    return n * amount


