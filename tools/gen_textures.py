def _leaf_polygon(cx, cy, length, width, ang, curl=0.0):
    pts = []
    n = 11
    for i in range(n):
        t = i / (n - 1.0)
        # width profile of a pointed leaf
        w = math.sin(math.pi * t) ** 0.65 * width
        off = curl * math.sin(math.pi * t)
        px = cx + math.cos(ang) * length * t + math.cos(ang + math.pi / 2) * (w + off)
        py = cy + math.sin(ang) * length * t + math.sin(ang + math.pi / 2) * (w + off)
        pts.append((px, py))
    for i in range(n - 1, -1, -1):
        t = i / (n - 1.0)
        w = math.sin(math.pi * t) ** 0.65 * width
        off = curl * math.sin(math.pi * t)
        px = cx + math.cos(ang) * length * t - math.cos(ang + math.pi / 2) * (w - off)
        py = cy + math.sin(ang) * length * t - math.sin(ang + math.pi / 2) * (w - off)
        pts.append((px, py))
    return pts


def _foliage_card(name, seed, count_back=14, width_mul=1.0, palette="jungle"):
    S = 512
    global rng
    rng = np.random.default_rng(seed)
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)

    def leaf(cx, cy, length, width, ang, tint, curl, alpha=255):
        pts = _leaf_polygon(cx, cy, length, width, ang, curl)
        d.polygon(pts, fill=(tint[0], tint[1], tint[2], alpha))
        d.line(
            [(cx, cy), (cx + math.cos(ang) * length * 0.96, cy + math.sin(ang) * length * 0.96)],
            fill=(max(0, tint[0] - 10), max(0, tint[1] - 14), max(0, tint[2] - 10), alpha),
            width=2,
        )
        # side veins
        for k in range(2, 9):
            t = k / 9.0
            bx = cx + math.cos(ang) * length * t
            by = cy + math.sin(ang) * length * t
            w = math.sin(math.pi * t) ** 0.5 * width * 0.7
            for side in (-1, 1):
                d.line(
                    [(bx, by), (bx + math.cos(ang + side * 1.0) * w, by + math.sin(ang + side * 1.0) * w)],
                    fill=(max(0, tint[0] - 8), max(0, tint[1] - 12), max(0, tint[2] - 8), alpha),
                    width=1,
                )

    # back layer: large dark leaves
    for i in range(count_back):
        ang = math.radians(float(rng.uniform(-172, -8)))
        length = float(rng.uniform(S * 0.45, S * 0.9))
        g = float(rng.uniform(0.55, 1.0))
        tint = (int(16 * g + 8), int(38 * g + 14), int(18 * g + 10))
        leaf(
            S * 0.5 + float(rng.uniform(-80, 80)),
            S * 1.02,
            length,
            float(rng.uniform(40, 70)) * width_mul,
            ang,
            tint,
            float(rng.uniform(-20, 20)),
        )
    # front layer: brighter, smaller leaves
    for i in range(count_back - 2):
        ang = math.radians(float(rng.uniform(-165, -15)))
        length = float(rng.uniform(S * 0.30, S * 0.62))
        g = float(rng.uniform(0.7, 1.15))
        tint = (int(26 * g + 10), int(56 * g + 20), int(28 * g + 12))
        leaf(
            S * 0.5 + float(rng.uniform(-130, 130)),
            S * 1.0,
            length,
            float(rng.uniform(30, 52)) * width_mul,
            ang,
            tint,
            float(rng.uniform(-22, 22)),
        )
    img = img.filter(ImageFilter.GaussianBlur(0.6))
    arr = np.asarray(img).astype(np.float32) / 255.0
    var = fbm(S, S, 8, 8, octaves=4, seed=seed + 3)
    rgb = np.clip(arr[..., :3] * (0.75 + 0.5 * var[..., None]), 0, 1)
    save_alpha(name, rgb, arr[..., 3])


